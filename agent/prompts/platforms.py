"""Platform-specific writing prompts and guidelines."""

BRUNCH_PROMPT = """브런치 플랫폼용 글을 작성합니다.

## 브런치 글쓰기 특징
- **독자**: 감성적이고 생각이 깊은 20-40대 한국인 독자
- **톤**: 따뜻하고 성찰적이며 문학적 감수성이 풍부
- **구조**: 도입부에 공감을 이끄는 경험/질문 → 본문 전개 → 여운 있는 마무리
- **길이**: 1,500~3,000자 (읽는 데 5~10분)
- **형식**: 소제목 활용, 적절한 줄바꿈, 시각적 여백

## 작성 지침
1. 첫 문장은 독자가 멈추게 만드는 문장으로 시작
2. 개인적인 경험이나 구체적인 에피소드를 중심으로 전개
3. 철학적 통찰이나 삶의 지혜를 자연스럽게 녹임
4. 독자가 자신의 이야기처럼 느낄 수 있게 서술
5. 마지막 문단은 독자에게 질문을 던지거나 여운을 남김

## 금지사항
- 딱딱한 보고서 형식
- 과도한 전문 용어
- 자기 자랑식 서술
"""

BLOG_PROMPT = """블로그(SEO 최적화) 글을 작성합니다.

## 블로그 글쓰기 특징
- **독자**: 특정 주제에 대한 정보를 검색하는 사용자
- **톤**: 전문적이지만 친근하고 실용적
- **구조**: 검색 의도 충족 → 핵심 정보 제공 → 실행 가능한 가이드
- **길이**: 2,000~4,000자 (심층 정보 제공)
- **형식**: H2/H3 소제목 체계, 불릿 포인트, 번호 리스트

## 작성 지침
1. 제목에 핵심 키워드 포함 (검색 의도 반영)
2. 도입부에서 독자의 문제/니즈를 명확히 언급
3. 목차 구성으로 스캐닝 독자 배려
4. 각 소제목 아래 구체적인 정보와 예시 제공
5. 내부/외부 링크를 위한 앵커 텍스트 자연스럽게 배치
6. 메타 설명용 요약 문장 포함

## SEO 요소
- 핵심 키워드를 제목, 첫 단락, 소제목에 자연스럽게 배치
- LSI 키워드(관련 검색어) 본문에 분산
- 이미지 ALT 텍스트 제안 포함
"""

INSTAGRAM_PROMPT = """인스타그램 캡션 및 콘텐츠를 작성합니다.

## 인스타그램 콘텐츠 특징
- **독자**: 시각적 콘텐츠를 즐기는 모든 연령대
- **톤**: 감성적, 영감을 주는, 또는 유머러스 (계정 성격에 따라)
- **구조**: 훅 문장(1-2줄) → 핵심 메시지(3-5줄) → CTA → 해시태그
- **길이**: 캡션 150-300자 (핵심), 해시태그 5-15개

## 작성 지침
1. 첫 줄은 더보기를 누르게 만드는 훅으로 시작
2. 이모지를 적절히 활용해 시각적 흐름 만들기
3. 줄바꿈을 통한 읽기 편한 구조
4. 행동 유도 문구(CTA): 저장, 공유, 댓글 유도
5. 해시태그: 대형(100만+) 2-3개, 중형(10만-100만) 5-7개, 소형(1만-10만) 3-5개 혼합

## 해시태그 전략
- 콘텐츠 관련 해시태그
- 타깃 커뮤니티 해시태그
- 브랜드 해시태그 (계정 고유 태그)

## 카드뉴스/릴스용 텍스트
- 슬라이드별 핵심 문구 (15자 이내)
- 스크롤을 멈추게 하는 표지 문구
"""

LINKEDIN_PROMPT = """링크드인 게시물을 작성합니다.

## 링크드인 콘텐츠 특징
- **독자**: 전문직 종사자, 취준생, 비즈니스 의사결정자
- **톤**: 전문적이지만 인간적, 통찰력 있고 영감을 주는
- **구조**: 강렬한 첫 줄 → 스토리/인사이트 → 배움/교훈 → 질문/CTA
- **길이**: 300-700자 (텍스트 게시물), 1,000-1,500자 (아티클)

## 작성 지침
1. 첫 줄은 '더 보기' 버튼 위에 노출 - 클릭 유도 필수
2. 개인적 경험에서 비롯된 비즈니스 인사이트 강조
3. 숫자와 구체적 성과로 신뢰성 구축
4. 업계 트렌드에 대한 독자적 시각 제시
5. 마지막에 토론을 유도하는 질문으로 마무리
6. 3-5개의 관련 해시태그 (소문자, 영어+한국어 혼용 가능)

## 고성과 포맷
- 숫자 기반 리스트: "XX하는 5가지 방법"
- Before/After 비교
- 실패 경험에서 배운 교훈
- 업계 관행에 대한 반론
- 커리어 성장 스토리
"""


def get_platform_prompt(platform: str) -> str:
    """Return the writing prompt for the specified platform."""
    prompts = {
        "brunch": BRUNCH_PROMPT,
        "blog": BLOG_PROMPT,
        "instagram": INSTAGRAM_PROMPT,
        "linkedin": LINKEDIN_PROMPT,
    }
    return prompts.get(platform.lower(), "")
